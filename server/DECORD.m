	; 29.10.26 SECURITY: EXTDATAMCALL REQUIRES A SESSION, MR TAKEN FROM THE TOKEN (NOT THE JOB),
	;          LOGIN LOCKOUT, ONE SESSION PER USER, LICENSED USERS LIST, LOGOUT, RELEASE AUDIT LOG.
	; GLOBALS (ALL UNDER ^MPG(MR,"DECORD")):
	;   "SESSION",TOKEN,...  ACTIVE SESSIONS           "BYUSER",OPC=TOKEN   CURRENT SESSION OF A USER
	;   "FAIL",OPC=COUNT_LASTSEC  FAILED LOGINS         "USERS",OPC=""       LICENSED USERS (EMPTY = ALL OPC USERS)
	;   "LOG",DATE,TIME,SEQ=OPC_ORDID_RESULT  RELEASE AUDIT
	Q
INIT	;
	I $G(JB)="" S JB=$J
	S MR=$$TOKENMR()
	I MR="" S MR=$G(^W(JB,"%DATA","MR"))
	I MR="" S MR=1
	;
	S ERR=""
	S CY=^MG(MR,35),UCI=^MG(MR,34)
	S LNGG=$S(^MG(MR,11)="E":2,1:1)
	S CODE="U"
	S CAV=$$CAV^%ZCAVV
	S D="_",C=":"
	Q
LOGIN	;
	I $G(JB)="" S JB=$J
	S ERR=""
	S CODE="U"
	S CAV=$$CAV^%ZCAVV
	S D="_",C=":"
	;
	N USER,PASS,RES,TOKEN
	S RES=$NA(^W(JB,"RES"))
	K @RES
	S USER=$G(%JSON("USER"))
	S PASS=$G(%JSON("PASS"))
	S MR=$G(%JSON("MR"))
	S TOKEN=""
	;
	; STOP AT THE FIRST ERROR - EMPTY USER/MR USED TO CRASH ON ^MG("") / ^T(...,"")
	D
	.I USER=""!($L(USER)>30) S ERR="ùîúùî øñç" Q
	.I PASS="" S ERR="äîñéñ äøñç" Q
	.I MR=""!($L(MR)>10) S ERR="äøáç øñç" Q
	.I '$D(^MG(MR)) S ERR="íéé÷ àì êøòî" Q
	.I $$LOCKED(USER) S ERR="äòù òáø ãåòá áåù äñð ,íéìùåë úåðåéñéð á÷ò úéðîæ íñçð ùîúùîä" Q
	.I '$$ISAUTH(USER,PASS) D FAILED(USER) S ERR="íééåâù äîñéñ åà ùîúùî íù" Q
	.I '$$ALLOWED(USER) S ERR="äéö÷éìôàì äàùøä ïéà ùîúùîì" Q
	.D CLRFAIL(USER)
	.S TOKEN=$$SESSION("START",USER)
	;
	S @RES@("ïë")=$S(ERR'="":"æáìóå",1:"ôòõå")
	S @RES@("åòòïò")=$S(ERR'="":$$WINH^%ZCAVS(ERR),1:"")
	S @RES@("îåøôPáçå")=$S(ERR="":"ïòäåòó_çòéä.èôíì",1:"")
	S @RES@("ôïëåî")=TOKEN
	S @RES@("USER")=USER
	I ERR="" S ^W(JB,"%DATA","MR")=MR
	W $$JSON^%ZCAVJSON(RES)
	Q
LOGOUT	;
	D INIT
	N TOKEN,X
	S TOKEN=$$CURTOKEN()
	I TOKEN'="" S X=$$SESSION("END",TOKEN)
	S RES=$NA(^W(JB,"RES","LOGOUT"))
	K @RES
	S @RES@("ïë")="ôòõå"
	W $$JSON^%ZCAVJSON(RES)
	Q
ISAUTH(USER,PASS)	;
	N ANS,UCICAV,A
	S UCICAV=$$CAV^%ZCAVV()
	S D="_"
	S ANS=0
	S A=$G(^[UCICAV]T("P","OPC",USER,"GN"))
	I A="" Q ANS
	I $P(A,D,10)'=PASS Q ANS
	S ANS=1
	Q ANS
ALLOWED(USER)	;
	; LICENSE: WHEN ^MPG(MR,"DECORD","USERS") HAS ENTRIES, ONLY THOSE USERS MAY LOG IN.
	; THE NUMBER OF ENTRIES = THE NUMBER OF LICENSED USERS FOR THIS COMPANY.
	I $D(^MPG(MR,"DECORD","USERS"))<10 Q 1
	Q $D(^MPG(MR,"DECORD","USERS",USER))>0
LOCKED(USER)	;
	; 5 FAILED LOGINS -> USER BLOCKED FOR 15 MINUTES FROM THE LAST FAILURE
	N A
	S A=$G(^MPG(MR,"DECORD","FAIL",USER))
	I +A<5 Q 0
	I $$NOWSEC()-$P(A,D,2)>900 K ^MPG(MR,"DECORD","FAIL",USER) Q 0
	Q 1
FAILED(USER)	;
	N A
	S A=$G(^MPG(MR,"DECORD","FAIL",USER))
	S ^MPG(MR,"DECORD","FAIL",USER)=(+A+1)_D_$$NOWSEC()
	Q
CLRFAIL(USER)	;
	K ^MPG(MR,"DECORD","FAIL",USER)
	Q
NOWSEC()	Q $P($H,",",1)*86400+$P($H,",",2)
AUTH(USERNAME,PASSWORD,LABEL)	;
	; ONLY LOGIN IS PUBLIC - EXTDATAMCALL (ORDERS, CUSTOMERS, PRICES) USED TO BE OPEN TO ANYONE
	I LABEL="LOGIN" Q 1
	N TOKEN,ANS
	S ANS=0
	S TOKEN=$$CURTOKEN()
	I TOKEN'="" S ANS=$$AUTHTOKEN(TOKEN)
	Q ANS
AUTHTOKEN(TOKEN)	;
	D INIT
	N ANS
	S ANS=$$SESSION("CHECK",TOKEN)
	Q ANS
	;
CURTOKEN()	;
	; TOKEN FROM HEADER AUTHORIZATION: BEARER <TOKEN>
	N TOKEN
	S TOKEN=$E($G(%HEADER("áõôèïòéúáôéïî")),8,999)
	I $L(TOKEN)>60 S TOKEN=""
	Q TOKEN
TOKENMR()	;
	; TOKENS ARE MR-RANDOM, SO THE COMPANY COMES WITH EVERY REQUEST INSTEAD OF FROM ^W(JB) OF WHATEVER JOB SERVES IT
	N TOKEN,M
	S TOKEN=$$CURTOKEN() I TOKEN="" Q ""
	S M=$P(TOKEN,"-",1) I M="" Q ""
	I '$D(^MG(M)) Q ""
	Q M
CURUSER()	;
	N TOKEN
	S TOKEN=$$CURTOKEN() I TOKEN="" Q ""
	Q $G(^MPG(MR,"DECORD","SESSION",TOKEN,"OPC"))
SESSION(OP,ARG)	;
	N SESSIONID,GLO,DATE,TIME,EXPDAT,EXPTIM,A,ANS,OLD
	S GLO=$NA(^MPG(MR,"DECORD"))
	;
	S OP=$G(OP),ANS="" D
	.I OP="START" D
	..S SESSIONID=MR_"-"_$$RANDOM^%ZCAVWEB(20)
	..I $D(@GLO@("SESSION",SESSIONID)) S SESSIONID=MR_"-"_$$RANDOM^%ZCAVWEB(20)
	..; ONE ACTIVE SESSION PER USER - A NEW LOGIN ENDS THE PREVIOUS ONE
	..S OLD=$G(@GLO@("BYUSER",ARG)) I OLD'="" K @GLO@("SESSION",OLD)
	..S @GLO@("BYUSER",ARG)=SESSIONID
	..S @GLO@("SESSION",SESSIONID,"EXPIRED-AT")=$$DATE^%ZDT($H+1,-2)_"-"_"02:00:00"
	..S @GLO@("SESSION",SESSIONID,"OPC")=ARG
	..S ANS=SESSIONID
	.;
	.I OP="END" D
	..S SESSIONID=ARG
	..S A=$G(@GLO@("SESSION",SESSIONID,"OPC"))
	..I A'="",$G(@GLO@("BYUSER",A))=SESSIONID K @GLO@("BYUSER",A)
	..K @GLO@("SESSION",SESSIONID)
	..S ANS=1
	.;
	.I OP="CHECK" D
	..S ANS=0
	..S SESSIONID=ARG
	..S A=$G(@GLO@("SESSION",SESSIONID,"EXPIRED-AT"))
	..S EXPDAT=$P(A,"-",1) Q:EXPDAT=""
	..S EXPTIM=$P(A,"-",2) Q:EXPTIM=""
	..S DATE=$$DATE^%ZDT(,-2)
	..S TIME=$$ZTIME^%ZDT()
	..I DATE>EXPDAT Q
	..I DATE=EXPDAT,$P(EXPTIM,C,1)<$P(TIME,C,1) Q
	..I DATE=EXPDAT,$P(EXPTIM,C,1)=$P(TIME,C,1),$P(EXPTIM,C,2)'>$P(TIME,C,2) Q
	..S ANS=1
	;
	Q ANS
	;
RELEASEORD	;
	D INIT
	N ORD,ORDID,OPC,RESULT
	S RES=$NA(^W(JB,"RES","Råìåáóå"))
	K @RES
	S %TIM=$$TIME^%ZCAVV(),%DAT=$$DATE^%ZDT(+$H,-2) ; SARITR 20050827
	S ORDID=$G(%JSON("ORDID"))
	S OPC=$$CURUSER()
	I OPC="" S OPC=$G(^W(JB,"RES","USER"))
	;
	; ONLY AN EXISTING, BLOCKED ORDER MAY BE RELEASED
	I ORDID=""!($L(ORDID)>30) S ERR="ïé÷ú àì äðîæä øôñî"
	I ERR="" S ORD="H"_ORDID I '$D(^MCO(MR,ORD,"F")) S ERR="äîåñç äðéà äðîæää"
	I ERR'="" D  Q
	.S @RES@("åòòïò")=$$WINH^%ZCAVS(ERR)
	.D LOG(ORDID,OPC,"REJECTED")
	.W $$JSON^%ZCAVJSON(RES)
	;
	ZA ^MCO(MR,ORD):0
	E  S ERR="øçà óåñîá úìôåèî-äìôåè àì "_ORDID
	I ERR'="" D  Q
	.S @RES@("éóLïãëåä")=$$WINH^%ZCAVS(ERR)
	.D LOG(ORDID,OPC,"LOCKED")
	.W $$JSON^%ZCAVJSON(RES)
	;
	S AP="ORDOPN"
	D UPDORD^ORDOPNL(ORD)
	S RESULT="RELEASED"
	;
	I $D(^MCO(MR,ORD,"F-CLOSERR")) D
	. S KODERR=$O(^MCO(MR,ORD,"F-CLOSERR",""))
	. S MSG=$G(^MCO(MR,ORD,"F-CLOSERR",KODERR))
	. S @RES@("Sôéìì-Bìïãë")=$$WINH^%ZCAVS("!äîéñçä úáéñá ìôèì àð, "_MSG_" : úåá÷òá äîñçð äðîæä")
	. S RESULT="STILL-BLOCK"
	;
	I $D(^MCO(MR,ORD,"F-OPEN")) D
	. S KODOP=$O(^MCO(MR,ORD,"F-OPEN",""))
	. S MSG=$G(^MCO(MR,ORD,"F-OPEN",KODOP))
	. S @RES@("Oðåî")=$$WINH^%ZCAVS(MSG_" : äîéñçä äøñåä äçúôð äðîæä")
	. I RESULT="RELEASED" S RESULT="OPEN"
	;
	I RESULT="RELEASED" S @RES@("Råìåáóåä")="ôòõå"
	ZD ^MCO(MR,ORD)
	D LOG(ORDID,OPC,RESULT)
	;
	W $$JSON^%ZCAVJSON(RES)
	Q
LOG(ORDID,OPC,RESULT)	;
	; AUDIT: WHO RELEASED WHICH ORDER AND WHEN
	N DAT,TIM,SEQ
	S DAT=$$DATE^%ZDT(,-2),TIM=$$ZTIME^%ZDT()
	S SEQ=$O(^MPG(MR,"DECORD","LOG",DAT,TIM,""),-1)+1
	S ^MPG(MR,"DECORD","LOG",DAT,TIM,SEQ)=OPC_D_ORDID_D_RESULT
	Q
EXTDATAMCALL	;FILLING THE ORDER LINES, SELECTING BY PREFERING THE ORDER PRICE OVER THE PRICE FOR THE CUSTOMER
	D INIT
	N LN,LNO,ORD,AORDL,DAT,HMCO,FDT1,TDT1
	S FDT1=$$DATE^%ZDT($H-1900,-2)
	S TDT1=$$DATE^%ZDT($H+300,-2)
	K ^W(JB,"RES","ORDERS")
	;
	S LN="",LNO=0
	S DAT=$O(^ME(MR,30,FDT1),-1)
	F  S DAT=$O(^ME(MR,30,DAT)) Q:DAT=""  Q:DAT>TDT1  D   ; YAIR 13.2.00
	. S HMCO=""
	. F  S HMCO=$O(^ME(MR,30,DAT,HMCO)) Q:HMCO=""  D
	. . Q:+$D(^MCO(MR,HMCO,"T"))
	. . Q:+$D(^MCO(MR,HMCO,"DLT"))   ;CHEN 12.2.19 #495444
	. . Q:+$D(^MCO(MR,HMCO,"PASS-ORD-TO-DNLG"))   ;CHEN 13.2.19 #495444
	. . Q:'$D(^MCO(MR,HMCO,"F"))    ;  úåøåâñ àì
	. . S LNO=LNO+1
	. . I $$FCLOSE(HMCO,LNO)=0 S LNO=LNO-1 Q
	. . D BLDW(HMCO,LNO)
	;
	W $$JSON^%ZCAVJSON($NA(^W(JB,"RES","ORDERS")))
	Q
BLDW(HORD,LNO)	;
	N KODCL
	;
	S ^W(JB,"RES","ORDERS",LNO,"ïòäåòIä")=$E(HORD,2,99)
	S A=$G(^MCO(MR,HORD))
	S LAK=$P(A,D,1)
	S LAK="H"_LAK,LAKNM=$$GETIND^SVEFUNC(LAK) ;çå÷ì íù
	S CUSTNAME=$$WINH^%ZCAVS(LAKNM)
	S ^W(JB,"RES","ORDERS",LNO,"ãõóôïíåòNáíå")=CUSTNAME
	;
	; RONAME WAS NOT RESET - AN ORDER WITHOUT AGENT SHOWED THE PREVIOUS ORDER'S AGENT
	S RONAME=""
	S RO=$P($G(^MCO(MR,HORD,"DS")),D,1)
	I RO'="" S RONAME=$P($G(^MT(MR,"RO",RO)),D,1) ;ùí ñåëï
	S AGENT=$$WINH^%ZCAVS(RONAME)
	S ^W(JB,"RES","ORDERS",LNO,"áçåîô")=AGENT
	;
	S FORDAT=$P(A,D,3)
	S ^W(JB,"RES","ORDERS",LNO,"ïòäåòDáôå")=$$DATE^%ZDT(FORDAT,".")
	;
	S TOTALVALUE=+$$VOL^SVCOVOL($E(HORD,2,99))
	S ^W(JB,"RES","ORDERS",LNO,"ôïôáìVáìõå")=TOTALVALUE
	;
	D BLDITM(HORD,LNO)
	Q
BLDITM(HORD,LNW)	;
	N LNO,AORDL
	S LNO=""
	F  S LNO=$O(^MCO(MR,HORD,"L",LNO)) Q:LNO=""  D
	. S AORDL=^MCO(MR,HORD,"L",LNO)
	. S ITMQUAN=+($P(AORDL,D,2)) ; SARITR 20250819 ADDIND +
	. S ITMPRICE=$P(AORDL,D,3)
	. S ITMPRICE=$P(ITMPRICE,":",1)
	. S ITMNUM=$P(AORDL,D,1)
	. S ORDDATE=$P(AORDL,D,3)
	. S CUSTPRICE=+$P($$NET^FUNCIT(LAK,ITMNUM,ITMQUAN,ORDDATE),D,2) ; SARITR 20250821
	. S FINALPRICE=+$S(ITMPRICE:ITMPRICE,CUSTPRICE:CUSTPRICE,1:0) ; SARITR 20250824
	. S TOTALPRICE=FINALPRICE*ITMQUAN ; SARITR 20250824
	. S FINALPRICE=$J(FINALPRICE,0,2) ; SARITR 20250824
	. S TOTALPRICE=$FN(TOTALPRICE,",",2) ; SARITR 20250828
	. S ITMDESC=$$WINH^%ZCAVS($P(^MP(MR,"H"_ITMNUM),D,1))
	. ;
	. S ^W(JB,"RES","ORDERS",LNW,"Iôåíó",LNO,"éôåíQõáîôéôù")=ITMQUAN ; SARITR 20250819 REPLACING UNITSQUAN WITH ITMQUAN
	. S ^W(JB,"RES","ORDERS",LNW,"Iôåíó",LNO,"éôåíDåóãòéðôéïî")=ITMDESC
	. S ^W(JB,"RES","ORDERS",LNW,"Iôåíó",LNO,"éôåíNõíâåò")=ITMNUM
	. S ^W(JB,"RES","ORDERS",LNW,"Iôåíó",LNO,"éôåíPòéãå")=FINALPRICE
	. S ^W(JB,"RES","ORDERS",LNW,"Iôåíó",LNO,"ôïôáìPòéãå")=TOTALPRICE
	Q
FCLOSE(HORD,LN)	;
	N L,L1,KODCL
	S (L1,FLG)=0
	S KODCL=""
	F  S KODCL=$O(^MCO(MR,HORD,"F-CLOSE",KODCL)) Q:KODCL=""  D
	. I ('$D(^MCO(MR,HORD,"F-OPEN",KODCL)))&('$D(^MCO(MR,HORD,"F-CLOSERR",KODCL))) Q
	. S L1=L1+1,FLG=1
	. S ^W(JB,"RES","ORDERS",LN,"F-CLOSE",L1)=$$WINH^%ZCAVS($P(^MCO(MR,HORD,"F-CLOSE",KODCL),D,1))
	. S L=""
	. F  S L=$O(^MCO(MR,HORD,"F-CLOSE",KODCL,L)) Q:L=""  D
	. . S L2=$O(^W(JB,"RES","ORDERS",LN,"Iôåíó",L,"ìéîåNïôå",""),-1)+1
	. . S ^W(JB,"RES","ORDERS",LN,"Iôåíó",L,"ìéîåNïôå",L2)=$$WINH^%ZCAVS($P(^MCO(MR,HORD,"F-CLOSE",KODCL,L),D,1))
	Q (FLG)
